package me.damoebe.GUI.editor.Canvas;

public class PixelPosition {
    private final int x;
    private final int y;

    public PixelPosition(int x, int y) {
        this.x = x;
        this.y = y;
    }

    public int getX() {
        return x;
    }

    public int getY() {
        return y;
    }
}
